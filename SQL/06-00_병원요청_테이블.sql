-- HOSPITAL_UPDATE_REQUEST.REQUEST_ID는 IDENTITY 컬럼이므로 별도 시퀀스를 직접 생성하지 않습니다.


/* 1. 시퀀스 */

CREATE SEQUENCE SEQ_HOSPITAL_OWNER_REQUEST START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE SEQUENCE SEQ_HOSPITAL_DELETE_HISTORY START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;


/* 2. 테이블 */

CREATE TABLE HOSPITAL_OWNER_REQUEST (
    REQUEST_ID NUMBER,
    MEMBER_ID NUMBER NOT NULL,
    HOSPITAL_ID NUMBER,
    BUSINESS_NUMBER VARCHAR2(50 CHAR) NOT NULL,
    DOCUMENT_URL VARCHAR2(1000 CHAR) NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    REJECT_REASON VARCHAR2(500 CHAR),
    CREATED_AT TIMESTAMP (6) DEFAULT SYSTIMESTAMP NOT NULL,
    PROCESSED_AT TIMESTAMP (6),
    APPLICANT_NAME VARCHAR2(100 CHAR) NOT NULL,
    HOSPITAL_NAME VARCHAR2(200 CHAR) NOT NULL,
    HOSPITAL_PHONE VARCHAR2(50 CHAR) NOT NULL,
    HOSPITAL_ADDRESS VARCHAR2(500 CHAR) NOT NULL,
    HOSPITAL_DETAIL_ADDRESS VARCHAR2(500 CHAR),
    HOSPITAL_DISTRICT VARCHAR2(50 CHAR) NOT NULL,
    HOSPITAL_WEBSITE_URL VARCHAR2(1000 CHAR),
    HOSPITAL_LATITUDE NUMBER(18,9) NOT NULL,
    HOSPITAL_LONGITUDE NUMBER(18,9) NOT NULL,
    HOSPITAL_OPEN_TIME VARCHAR2(1000 CHAR) NOT NULL,
    HOSPITAL_CLOSE_TIME VARCHAR2(1000 CHAR) NOT NULL,
    HOSPITAL_BREAK_TIME VARCHAR2(1000 CHAR),
    HOSPITAL_CLOSED_DAYS VARCHAR2(500 CHAR),
    HOSPITAL_MEDICAL_SUBJECTS VARCHAR2(2000 CHAR),
    HOSPITAL_DOCTOR_INFO VARCHAR2(1000 CHAR),
    HOSPITAL_DESCRIPTION VARCHAR2(2000 CHAR) NOT NULL,
    HOSPITAL_IMAGE_URL VARCHAR2(1000 CHAR) NOT NULL,
    HOSPITAL_NOTE VARCHAR2(2000 CHAR),
    PROCESSED_BY NUMBER,
    RESULT_READ_YN CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT CK_OWNER_REQUEST_STATUS CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT PK_HOSPITAL_OWNER_REQUEST PRIMARY KEY (REQUEST_ID),
    CONSTRAINT CK_OWNER_REQUEST_HOSPITAL CHECK (
           (STATUS = 'PENDING' AND HOSPITAL_ID IS NULL)
        OR (STATUS = 'REJECTED' AND HOSPITAL_ID IS NULL)
        OR (STATUS = 'APPROVED')
    ),
    CONSTRAINT CK_OWNER_REQ_RESULT_READ CHECK (RESULT_READ_YN IN ('Y', 'N'))
);

CREATE TABLE OWNER_REQUEST_ANIMAL (
    REQUEST_ID NUMBER NOT NULL,
    ANIMAL_ID NUMBER NOT NULL,
    CONSTRAINT PK_OWNER_REQUEST_ANIMAL PRIMARY KEY (REQUEST_ID, ANIMAL_ID)
);

CREATE TABLE OWNER_REQUEST_SERVICE (
    REQUEST_ID NUMBER NOT NULL,
    SERVICE_ID NUMBER NOT NULL,
    CONSTRAINT PK_OWNER_REQUEST_SERVICE PRIMARY KEY (REQUEST_ID, SERVICE_ID)
);

CREATE TABLE OWNER_REQUEST_MEDICAL_SUBJECT (
    REQUEST_ID NUMBER NOT NULL,
    SUBJECT_ID NUMBER NOT NULL,
    CONSTRAINT PK_OWNER_REQ_MED_SUBJ PRIMARY KEY (REQUEST_ID, SUBJECT_ID)
);

CREATE TABLE HOSPITAL_UPDATE_REQUEST (
    REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    HOSPITAL_ID NUMBER NOT NULL,
    MEMBER_ID NUMBER NOT NULL,
    REQUEST_TYPE VARCHAR2(20) DEFAULT 'UPDATE' NOT NULL,
    APPLICANT_NAME VARCHAR2(50),
    BUSINESS_NUMBER VARCHAR2(30),
    DOCUMENT_URL VARCHAR2(1000),
    HOSPITAL_NAME VARCHAR2(200),
    HOSPITAL_PHONE VARCHAR2(50),
    HOSPITAL_ADDRESS VARCHAR2(500),
    HOSPITAL_DETAIL_ADDRESS VARCHAR2(500),
    HOSPITAL_DISTRICT VARCHAR2(50),
    HOSPITAL_WEBSITE_URL VARCHAR2(1000),
    HOSPITAL_LATITUDE NUMBER(18,9),
    HOSPITAL_LONGITUDE NUMBER(18,9),
    MEDICAL_SUBJECTS VARCHAR2(2000),
    OPEN_TIME VARCHAR2(100),
    CLOSE_TIME VARCHAR2(100),
    BREAK_TIME VARCHAR2(100),
    CLOSED_DAYS VARCHAR2(500),
    HOSPITAL_DOCTOR_INFO VARCHAR2(1000),
    HOSPITAL_DESCRIPTION VARCHAR2(2000),
    HOSPITAL_IMAGE_URL VARCHAR2(1000),
    HOSPITAL_NOTE VARCHAR2(2000),
    TEMP_CLOSE_START_AT TIMESTAMP (6),
    TEMP_CLOSE_END_AT TIMESTAMP (6),
    REQUEST_REASON VARCHAR2(500),
    STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    CREATED_AT TIMESTAMP (6) DEFAULT SYSTIMESTAMP NOT NULL,
    PROCESSED_AT TIMESTAMP (6),
    PROCESSED_BY NUMBER,
    REJECT_REASON VARCHAR2(1000),
    CONSTRAINT CK_HUR_REQUEST_TYPE CHECK (REQUEST_TYPE IN ('UPDATE', 'TEMP_CLOSE', 'CLOSE')),
    CONSTRAINT CK_HUR_STATUS CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT CK_HUR_TEMP_CLOSE_PERIOD CHECK (
                                                     REQUEST_TYPE != 'TEMP_CLOSE'
                                                     OR (
                                                     TEMP_CLOSE_START_AT IS NOT NULL
                                                     AND TEMP_CLOSE_END_AT IS NOT NULL
                                                     AND TEMP_CLOSE_END_AT > TEMP_CLOSE_START_AT
                                                     )
    ),
    CONSTRAINT PK_HOSPITAL_UPDATE_REQUEST PRIMARY KEY (REQUEST_ID)
);

CREATE TABLE HOSPITAL_UPDATE_REQUEST_ANIMAL (
    REQUEST_ID NUMBER NOT NULL,
    ANIMAL_ID NUMBER NOT NULL,
    CONSTRAINT PK_HUR_ANIMAL PRIMARY KEY (REQUEST_ID, ANIMAL_ID)
);

CREATE TABLE HOSPITAL_UPDATE_REQUEST_SERVICE (
    REQUEST_ID NUMBER NOT NULL,
    SERVICE_ID NUMBER NOT NULL,
    CONSTRAINT PK_HUR_SERVICE PRIMARY KEY (REQUEST_ID, SERVICE_ID)
);

CREATE TABLE HOSPITAL_UPDATE_REQUEST_MEDICAL_SUBJECT (
    REQUEST_ID NUMBER NOT NULL,
    SUBJECT_ID NUMBER NOT NULL,
    CONSTRAINT PK_HUR_SUBJECT PRIMARY KEY (REQUEST_ID, SUBJECT_ID)
);

CREATE TABLE HOSPITAL_DELETE_HISTORY (
    DELETE_HISTORY_ID NUMBER,
    HOSPITAL_ID NUMBER NOT NULL,
    HOSPITAL_NAME VARCHAR2(200) NOT NULL,
    OWNER_ID NUMBER,
    OWNER_NAME VARCHAR2(100),
    CLOSE_REQUEST_ID NUMBER,
    DELETE_REASON VARCHAR2(1000),
    CLOSED_AT TIMESTAMP (6),
    DELETED_AT TIMESTAMP (6) DEFAULT SYSTIMESTAMP NOT NULL,
    DELETED_BY NUMBER NOT NULL,
    CONSTRAINT HOSPITAL_DELETE_HISTORY_PK PRIMARY KEY (DELETE_HISTORY_ID)
);


