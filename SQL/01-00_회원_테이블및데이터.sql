DECLARE
    V_PASSWORD CONSTANT VARCHAR2(200) :=
        '$2a$10$CIU/6.QNVORtdY41VTyVje2cmIKfzPYud.sZ8GGmCO8dtqWid0CEi';

    V_STATUS              APP_MEMBER.STATUS%TYPE;
    V_MEMBER_STATUS       APP_MEMBER.MEMBER_STATUS%TYPE;
    V_LAST_LOGIN_AT       APP_MEMBER.LAST_LOGIN_AT%TYPE;
    V_BLOCKED_AT          APP_MEMBER.BLOCKED_AT%TYPE;
    V_DELETE_REQUESTED_AT APP_MEMBER.DELETE_REQUESTED_AT%TYPE;
    V_DELETED_AT          APP_MEMBER.DELETED_AT%TYPE;
    V_HARD_DELETE_AT      APP_MEMBER.HARD_DELETE_AT%TYPE;
    V_DELETE_REASON       APP_MEMBER.DELETE_REASON%TYPE;
BEGIN
    FOR I IN 1..200 LOOP
        V_BLOCKED_AT := NULL;
        V_DELETE_REQUESTED_AT := NULL;
        V_DELETED_AT := NULL;
        V_HARD_DELETE_AT := NULL;
        V_DELETE_REASON := NULL;

        IF I <= 180 THEN
            V_STATUS := 'ACTIVE';
            V_MEMBER_STATUS := 'ACTIVE';
            V_LAST_LOGIN_AT :=
                LOCALTIMESTAMP
                - NUMTODSINTERVAL(MOD(I, 90), 'DAY');
        ELSE
            V_STATUS := 'DELETED';
            V_MEMBER_STATUS := 'DELETED';
            V_LAST_LOGIN_AT := ADD_MONTHS(LOCALTIMESTAMP, -13);
            V_DELETE_REQUESTED_AT := LOCALTIMESTAMP - INTERVAL '1' DAY;
            V_DELETED_AT := LOCALTIMESTAMP - INTERVAL '1' DAY;
            V_HARD_DELETE_AT := LOCALTIMESTAMP + INTERVAL '30' DAY;
            V_DELETE_REASON := '테스트용 삭제 상태 회원';
        END IF;

        INSERT INTO APP_MEMBER (
            MEMBER_ID,
            LOGIN_ID,
            PASSWORD,
            NICKNAME,
            EMAIL,
            PHONE,
            ROLE,
            CREATED_AT,
            UPDATED_AT,
            PROFILE_IMAGE,
            EMAIL_VERIFIED,
            STATUS,
            LAST_LOGIN_AT,
            MEMBER_STATUS,
            DELETE_REQUESTED_AT,
            HARD_DELETE_AT,
            DELETED_AT,
            BLOCKED_AT,
            DELETE_REASON
        )
        SELECT
            SEQ_APP_MEMBER.NEXTVAL,
            'test' || LPAD(I, 3, '0'),
            V_PASSWORD,
            '테스트회원' || LPAD(I, 3, '0'),
            'test' || LPAD(I, 3, '0') || '@petcity.test',
            '010-9000-' || LPAD(I, 4, '0'),
            'USER',
            LOCALTIMESTAMP - NUMTODSINTERVAL(MOD(I, 180), 'DAY'),
            LOCALTIMESTAMP,
            NULL,
            'Y',
            V_STATUS,
            V_LAST_LOGIN_AT,
            V_MEMBER_STATUS,
            V_DELETE_REQUESTED_AT,
            V_HARD_DELETE_AT,
            V_DELETED_AT,
            V_BLOCKED_AT,
            V_DELETE_REASON
        FROM DUAL
        WHERE NOT EXISTS (
            SELECT 1
            FROM APP_MEMBER
            WHERE LOGIN_ID = 'test' || LPAD(I, 3, '0')
        );
    END LOOP;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
