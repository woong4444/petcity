/* 1. 시퀀스 */

CREATE SEQUENCE SEQ_APP_MEMBER START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE SEQUENCE SEQ_MEMBER_SECURITY_AUDIT START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;


/* 2. 테이블 */

CREATE TABLE APP_MEMBER (
    MEMBER_ID NUMBER,
    NICKNAME VARCHAR2(50 CHAR) NOT NULL,
    EMAIL VARCHAR2(100 CHAR),
    PHONE VARCHAR2(30 CHAR),
    ROLE VARCHAR2(20 CHAR) DEFAULT 'USER' NOT NULL,
    CREATED_AT TIMESTAMP (6) DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP (6),
    PROFILE_IMAGE VARCHAR2(1000 CHAR),
    LOGIN_ID VARCHAR2(150 CHAR) NOT NULL,
    PASSWORD VARCHAR2(200 CHAR) NOT NULL,
    EMAIL_VERIFIED CHAR(1) DEFAULT 'N' NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    LAST_LOGIN_AT TIMESTAMP (6),
    MEMBER_STATUS VARCHAR2(30 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    DELETE_REQUESTED_AT TIMESTAMP (6),
    HARD_DELETE_AT TIMESTAMP (6),
    DELETED_AT TIMESTAMP (6),
    DELETE_REASON VARCHAR2(500),
    BLOCKED_AT TIMESTAMP (6),
    BLOCKED_BY NUMBER,
    LOGIN_TYPE VARCHAR2(20),
    SOCIAL_ID VARCHAR2(100),
    AGREEMENT_EMAIL CHAR(1) DEFAULT 'N',
    RECOVERY_TOKEN_HASH VARCHAR2(200 CHAR),
    CONSTRAINT CK_APP_MEMBER_ROLE CHECK (ROLE IN ('USER', 'OWNER', 'ADMIN')),
    CONSTRAINT CK_APP_MEMBER_EMAIL_VERIFIED CHECK (EMAIL_VERIFIED IN ('Y', 'N')),
    CONSTRAINT CK_APP_MEMBER_STATUS CHECK (STATUS IN ('ACTIVE', 'BLOCKED', 'DELETED')),
    CONSTRAINT CK_APP_MEMBER_MEMBER_STATUS CHECK (MEMBER_STATUS IN ('ACTIVE', 'DELETE_PENDING', 'DELETED')),
    CONSTRAINT PK_APP_MEMBER PRIMARY KEY (MEMBER_ID),
    CONSTRAINT UQ_APP_MEMBER_LOGIN_ID UNIQUE (LOGIN_ID)
);

CREATE TABLE MEMBER_SECURITY_AUDIT (
    AUDIT_ID NUMBER,
    MEMBER_ID NUMBER,
    LOGIN_ID VARCHAR2(100 CHAR) NOT NULL,
    NICKNAME VARCHAR2(100 CHAR),
    LOGIN_TYPE VARCHAR2(30 CHAR),
    EVENT_TYPE VARCHAR2(50 CHAR) NOT NULL,
    EVENT_RESULT VARCHAR2(20 CHAR) NOT NULL,
    EVENT_REASON VARCHAR2(1000 CHAR),
    IP_ADDRESS VARCHAR2(64 CHAR),
    OCCURRED_AT TIMESTAMP (6) DEFAULT SYSTIMESTAMP NOT NULL,
    EXPIRES_AT TIMESTAMP (6) NOT NULL,
    CONSTRAINT CK_MEMBER_SECURITY_AUDIT_RESULT CHECK (EVENT_RESULT IN ('SUCCESS', 'FAILURE')),
    CONSTRAINT PK_MEMBER_SECURITY_AUDIT PRIMARY KEY (AUDIT_ID)
);


/* 4. 조회·업무 인덱스 */

CREATE INDEX IX_MEMBER_SECURITY_AUDIT_MEMBER
    ON MEMBER_SECURITY_AUDIT (MEMBER_ID, OCCURRED_AT DESC);

CREATE INDEX IX_MEMBER_SECURITY_AUDIT_EXPIRES
    ON MEMBER_SECURITY_AUDIT (EXPIRES_AT);


COMMIT;



